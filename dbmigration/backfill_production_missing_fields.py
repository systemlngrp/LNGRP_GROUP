"""Backfill blank productions fields from Daily Production Master.

Dry-run by default. Only NULL/blank database fields are filled; populated values,
transaction numbers, and job-card numbers are never overwritten.
"""
from __future__ import annotations

import argparse
import re
from collections import defaultdict
from pathlib import Path

from migrate_daily_bk_orders_jobs import (
    SHEET_ID, credentials, connect, load_runtime_env, safe_rollback, sheets_values, s,
)

DEFAULT_BATCH_SIZE = 100
SHEET_NAME = "Daily Production Master"
PROTECTED = {
    "id", "transactionNo", "jobCardNo", "status", "updatedBy", "updateTimestamp",
    "tallyTimestamp", "tallyPostingStatus", "tallyVoucherNo", "tallyVoucherDate",
    "tallyVoucherId", "tallyPostedBy", "tallyPostingRemark", "tallyPostingError",
    "tallyLastAttemptAt", "tallyPostingAttemptCount", "cancelTimestamp", "cancelEmailId",
    "cancelRemarks", "closeBy", "closeDate", "orderFirmId", "sourceFirmId",
    "destinationFirmId", "sourceTransactionType", "sourceTransactionId", "interFirmFlow",
    "autoGenerated", "mrrSource", "linkedGateEntryId", "linkedMrrId", "linkedInvoiceId",
    "reelTransferId", "reelTransferTimestamp",
}
DATE_FIELDS = {"date", "scheduledDate"}
ALIASES = {
    "jobcardno": "jobCardNo", "jobcard": "jobCardNo", "jobcardnumber": "jobCardNo",
    "erp": "erpCode", "erpcode": "erpCode", "mastererp": "masterErp",
    "scheduleddate": "scheduledDate", "productioninmeter": "productionInMeter",
    "plannedproductioninmeter": "plannedProductionInMeter", "requiredqty": "requiredQty",
    "plannedqty": "plannedQty", "productionoutputqty": "productionOutputQty",
    "actualpaperused": "actualPaperUsed", "company": "companyName",
}


def norm(value):
    return re.sub(r"[^a-z0-9]", "", s(value).lower())


def job_key(value):
    value = s(value)
    if re.fullmatch(r"\d+\.0", value):
        value = value[:-2]
    return value.upper()


def blank(value):
    return value is None or s(value) == ""


def parse_args():
    p = argparse.ArgumentParser(description="Backfill blank production fields from Daily Production Master")
    p.add_argument("--apply", action="store_true")
    p.add_argument("--batch-size", type=int, default=DEFAULT_BATCH_SIZE)
    p.add_argument("--start-batch", type=int, default=1)
    p.add_argument("--max-batches", type=int)
    return p.parse_args()


def read_sheet():
    result = sheets_values().get(spreadsheetId=SHEET_ID, range=f"'{SHEET_NAME}'!A:ZZ").execute()
    raw = result.get("values", [])
    if not raw:
        raise RuntimeError("Daily Production Master returned no rows")
    headers = [s(v) for v in raw[0]]
    columns = {}
    for i, header in enumerate(headers):
        key = norm(header)
        if key and key not in columns:
            columns[key] = i
    job_index = next((columns[k] for k in ("jobcardno", "jobcard", "jobcardnumber") if k in columns), 2)
    rows = []
    for row_number, values in enumerate(raw[1:], 2):
        card = job_key(values[job_index] if job_index < len(values) else "")
        if not card:
            continue
        item = {"_row": row_number, "jobCardNo": card}
        for key, index in columns.items():
            if index >= len(values) or blank(values[index]):
                continue
            field = ALIASES.get(key, next((x for x in headers if norm(x) == key), ""))
            if field:
                item[field] = s(values[index])
        rows.append(item)
    grouped = defaultdict(list)
    for item in rows:
        grouped[item["jobCardNo"]].append(item)
    unique, ambiguous = {}, {}
    for card, items in grouped.items():
        signatures = {tuple(sorted((k, v) for k, v in x.items() if k not in {"_row", "jobCardNo"})) for x in items}
        if len(signatures) == 1:
            unique[card] = items[0]
        else:
            ambiguous[card] = items
    return unique, ambiguous, len(raw) - 1


def load_candidates(cur, source):
    cur.execute("SELECT * FROM productions ORDER BY id")
    columns = [x[0] for x in cur.description]
    candidates, unmatched = [], []
    for values in cur.fetchall():
        row = dict(zip(columns, values))
        card = job_key(row.get("jobCardNo"))
        item = source.get(card)
        if not item:
            unmatched.append(row["id"])
            continue
        updates = {}
        for field, value in item.items():
            if field.startswith("_") or field in PROTECTED or field not in columns or field == "jobCardNo":
                continue
            if field in DATE_FIELDS:
                continue
            if blank(row.get(field)) and not blank(value):
                updates[field] = value
        if updates:
            candidates.append({"id": row["id"], "jobCardNo": card, "updates": updates})
    return candidates, unmatched


def chunks(items, size):
    for i in range(0, len(items), size):
        yield items[i:i + size]


def main():
    load_runtime_env()
    args = parse_args()
    if args.batch_size <= 0 or args.start_batch <= 0 or (args.max_batches is not None and args.max_batches <= 0):
        raise SystemExit("batch-size, start-batch, and max-batches must be positive")
    source, ambiguous, scanned = read_sheet()
    db = connect()
    try:
        cur = db.cursor()
        candidates, unmatched = load_candidates(cur, source)
        batches = list(chunks(candidates, args.batch_size))
        selected = batches[args.start_batch - 1: args.start_batch - 1 + args.max_batches if args.max_batches else None]
        print(f"Source rows scanned: {scanned}")
        print(f"Unique job cards: {len(source)}")
        print(f"Ambiguous job cards skipped: {len(ambiguous)}")
        print(f"Productions with no matching sheet job card: {len(unmatched)}")
        print(f"Records needing backfill: {len(candidates)}; batches: {len(batches)}; selected: {len(selected)}")
        for batch_no, batch in enumerate(selected, args.start_batch):
            field_count = sum(len(x["updates"]) for x in batch)
            print(f"Batch {batch_no}: records={len(batch)}; fields={field_count}")
            for record in batch:
                for field, value in record["updates"].items():
                    print(f"  Production {record['id']} jobCardNo={record['jobCardNo']} field={field} old=NULL new={value!r}")
            if args.apply:
                try:
                    for record in batch:
                        fields = list(record["updates"])
                        sql = "UPDATE productions SET " + ", ".join(f"`{f}`=%s" for f in fields) + " WHERE id=%s"
                        cur.execute(sql, [record["updates"][f] for f in fields] + [record["id"]])
                    db.commit()
                    print(f"Batch {batch_no}: committed records={len(batch)}")
                except Exception:
                    safe_rollback(db)
                    raise
        if not args.apply:
            print("DRY RUN: no database changes committed.")
    finally:
        db.close()


if __name__ == "__main__":
    main()
